def day_label(dt: datetime, tz: str, lang: str) -> str:
    local = dt.astimezone(ZoneInfo(tz))
    if lang == "vi":
        return f"{VI_DAYS[local.weekday()]}, {local.day:02d}/{local.month:02d}"
    return local.strftime("%a %d %b")


